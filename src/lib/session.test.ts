import { AxiosError, AxiosHeaders } from "axios";
import { get } from "svelte/store";
import { beforeEach, describe, expect, it, vi } from "vitest";

import { API_BASE } from "#lib/api-base.js";

// Mock axios to prevent real API calls
vi.mock("#lib/axios.js", () => ({
	default: {
		get: vi.fn(),
		post: vi.fn(),
	},
}));

// Fresh session store for each test
async function createTestSession() {
	vi.resetModules();
	const { session } = await import("#lib/session.js");
	return session;
}

// Helper: seed a session into the store by calling init() with
// pre-populated localStorage
function seedStorage(data: {
	username: string;
	token: string;
	savedPlaces: number[];
	savedAreas?: number[];
}) {
	localStorage.setItem("btcmap_session", JSON.stringify(data));
}

describe("session store", () => {
	beforeEach(() => {
		localStorage.clear();
		vi.restoreAllMocks();
	});

	describe("toggleSavedPlace", () => {
		it("adds a place when not already saved", async () => {
			seedStorage({
				username: "test",
				token: "tok",
				savedPlaces: [1, 2],
				savedAreas: [],
			});
			const session = await createTestSession();
			session.init();

			const result = session.toggleSavedPlace(3);
			expect(result).toEqual([1, 2, 3]);
			expect(get(session)?.savedPlaces).toEqual([1, 2, 3]);
		});

		it("removes a place when already saved", async () => {
			seedStorage({
				username: "test",
				token: "tok",
				savedPlaces: [1, 2, 3],
				savedAreas: [],
			});
			const session = await createTestSession();
			session.init();

			const result = session.toggleSavedPlace(2);
			expect(result).toEqual([1, 3]);
			expect(get(session)?.savedPlaces).toEqual([1, 3]);
		});

		it("returns null when no session exists", async () => {
			const session = await createTestSession();
			const result = session.toggleSavedPlace(1);
			expect(result).toBeNull();
		});

		it("persists to localStorage", async () => {
			seedStorage({
				username: "test",
				token: "tok",
				savedPlaces: [],
				savedAreas: [],
			});
			const session = await createTestSession();
			session.init();

			session.toggleSavedPlace(42);

			const stored = JSON.parse(localStorage.getItem("btcmap_session") ?? "{}");
			expect(stored.savedPlaces).toEqual([42]);
		});
	});

	describe("toggleSavedArea", () => {
		it("adds an area when not already saved", async () => {
			seedStorage({
				username: "test",
				token: "tok",
				savedPlaces: [],
				savedAreas: [10],
			});
			const session = await createTestSession();
			session.init();

			const result = session.toggleSavedArea(20);
			expect(result).toEqual([10, 20]);
		});

		it("removes an area when already saved", async () => {
			seedStorage({
				username: "test",
				token: "tok",
				savedPlaces: [],
				savedAreas: [10, 20],
			});
			const session = await createTestSession();
			session.init();

			const result = session.toggleSavedArea(10);
			expect(result).toEqual([20]);
		});
	});

	describe("loadFromStorage backfill", () => {
		it("backfills savedAreas when missing from old session", async () => {
			localStorage.setItem(
				"btcmap_session",
				JSON.stringify({
					username: "old-user",
					token: "old-tok",
					savedPlaces: [1, 2],
				}),
			);
			const session = await createTestSession();
			session.init();

			const current = get(session);
			expect(current?.savedAreas).toEqual([]);
			expect(current?.savedPlaces).toEqual([1, 2]);
		});

		// #1325: legacy throwaway sessions carried their password in
		// localStorage for the retired backup modal
		it("drops a legacy throwaway's password and flag, in storage too", async () => {
			localStorage.setItem(
				"btcmap_session",
				JSON.stringify({
					username: "old-user",
					password: "random-pw",
					token: "old-tok",
					savedPlaces: [1],
					savedAreas: [2],
					autoGenerated: true,
					npub: null,
				}),
			);
			const session = await createTestSession();
			session.init();

			expect(get(session)).toEqual({
				username: "old-user",
				token: "old-tok",
				savedPlaces: [1],
				savedAreas: [2],
				npub: null,
			});
			const stored = JSON.parse(localStorage.getItem("btcmap_session") ?? "{}");
			expect(stored).not.toHaveProperty("password");
			expect(stored).not.toHaveProperty("autoGenerated");
			expect(stored.token).toBe("old-tok");
		});

		it("leaves a current-shape session in storage untouched", async () => {
			const raw = JSON.stringify({
				username: "alice",
				token: "tok",
				savedPlaces: [],
				savedAreas: [],
				npub: null,
			});
			localStorage.setItem("btcmap_session", raw);
			const setItem = vi.spyOn(Storage.prototype, "setItem");
			const session = await createTestSession();
			session.init();

			expect(setItem).not.toHaveBeenCalled();
			expect(localStorage.getItem("btcmap_session")).toBe(raw);
		});

		it("backfills npub to null when missing from old session", async () => {
			localStorage.setItem(
				"btcmap_session",
				JSON.stringify({
					username: "old-user",
					token: "old-tok",
					savedPlaces: [1],
					savedAreas: [],
				}),
			);
			const session = await createTestSession();
			session.init();

			const current = get(session);
			expect(current?.npub).toBeNull();
		});

		it("returns null for invalid data", async () => {
			localStorage.setItem("btcmap_session", "not-json");
			const session = await createTestSession();
			session.init();
			expect(get(session)).toBeNull();
		});

		it("returns null when username is missing", async () => {
			localStorage.setItem(
				"btcmap_session",
				JSON.stringify({ token: "tok", savedPlaces: [] }),
			);
			const session = await createTestSession();
			session.init();
			expect(get(session)).toBeNull();
		});
	});

	describe("signUp with chosen credentials", () => {
		// api.post is a shared vi.fn across tests; reset calls + implementations
		// so assertions on call counts and bodies don't leak between cases.
		async function postMock() {
			const { default: api } = await import("#lib/axios.js");
			const post = api.post as ReturnType<typeof vi.fn>;
			post.mockReset();
			return post;
		}

		it("sends the chosen username and password to the API", async () => {
			const post = await postMock();
			post
				.mockResolvedValueOnce({ data: { name: "alice" } })
				.mockResolvedValueOnce({ data: { token: "tok" } });
			const session = await createTestSession();

			await session.signUp({
				username: "alice",
				password: "correct horse battery",
			});

			expect(post).toHaveBeenCalledWith(`${API_BASE}/v4/users`, {
				name: "alice",
				password: "correct horse battery",
			});
			expect(post).toHaveBeenCalledWith(
				`${API_BASE}/v4/users/alice/tokens`,
				{ label: "BTC Map Web" },
				{ headers: { Authorization: "Bearer correct horse battery" } },
			);
		});

		it("keeps a chosen password out of the stored session", async () => {
			const post = await postMock();
			post
				.mockResolvedValueOnce({ data: { name: "alice" } })
				.mockResolvedValueOnce({ data: { token: "tok" } });
			const session = await createTestSession();

			const current = await session.signUp({
				username: "alice",
				password: "correct horse battery",
			});

			expect(current).not.toHaveProperty("password");
			expect(localStorage.getItem("btcmap_session")).not.toContain(
				"correct horse battery",
			);
		});

		it("trims the username before sending it", async () => {
			const post = await postMock();
			post
				.mockResolvedValueOnce({ data: { name: "bob" } })
				.mockResolvedValueOnce({ data: { token: "tok" } });
			const session = await createTestSession();

			await session.signUp({
				username: "  bob  ",
				password: "correct horse battery",
			});

			expect(post).toHaveBeenCalledWith(`${API_BASE}/v4/users`, {
				name: "bob",
				password: "correct horse battery",
			});
		});

		it("rejects a blank username", async () => {
			const post = await postMock();
			const session = await createTestSession();

			await expect(
				session.signUp({ username: "   ", password: "correct horse battery" }),
			).rejects.toThrow();
			expect(post).not.toHaveBeenCalled();
		});
	});

	describe("login", () => {
		it("persists the npub for a Nostr login", async () => {
			const session = await createTestSession();
			session.login("nostr-user", "tok", "npub1example");

			const current = get(session);
			expect(current?.npub).toBe("npub1example");

			const stored = JSON.parse(localStorage.getItem("btcmap_session") ?? "{}");
			expect(stored.npub).toBe("npub1example");
		});

		it("defaults npub to null for a password login", async () => {
			const session = await createTestSession();
			session.login("pw-user", "tok");

			expect(get(session)?.npub).toBeNull();
		});
	});

	describe("logout", () => {
		async function postMock() {
			const { default: api } = await import("#lib/axios.js");
			const post = api.post as ReturnType<typeof vi.fn>;
			post.mockReset();
			return post;
		}

		it("clears the session before the revoke settles", async () => {
			const post = await postMock();
			post.mockReturnValueOnce(new Promise(() => {}));
			seedStorage({ username: "alice", token: "tok", savedPlaces: [] });
			const session = await createTestSession();
			session.init();

			void session.logout();

			expect(get(session)).toBeNull();
			expect(localStorage.getItem("btcmap_session")).toBeNull();
		});

		it("revokes the logged-out token on the API", async () => {
			const post = await postMock();
			post.mockResolvedValueOnce({ data: { id: 1, label: "BTC Map Web" } });
			seedStorage({ username: "alice", token: "tok", savedPlaces: [] });
			const session = await createTestSession();
			session.init();

			await session.logout();

			expect(post).toHaveBeenCalledWith(`${API_BASE}/v4/auth/signout`, null, {
				headers: { Authorization: "Bearer tok" },
			});
		});

		it("resolves when the revoke fails", async () => {
			const post = await postMock();
			post.mockRejectedValueOnce(new Error("offline"));
			vi.spyOn(console, "warn").mockImplementation(() => {});
			seedStorage({ username: "alice", token: "tok", savedPlaces: [] });
			const session = await createTestSession();
			session.init();

			await expect(session.logout()).resolves.toBeUndefined();
			expect(get(session)).toBeNull();
		});

		it("calls nothing without a session", async () => {
			const post = await postMock();
			const session = await createTestSession();

			await session.logout();

			expect(post).not.toHaveBeenCalled();
		});
	});

	describe("setUsername / setNpub", () => {
		const current = { stillCurrent: () => true };
		const stale = { stillCurrent: () => false };

		it("setUsername renames the session and persists it", async () => {
			seedStorage({ username: "alice", token: "tok", savedPlaces: [1] });
			const session = await createTestSession();
			session.init();

			session.setUsername(current, "alice2");

			expect(get(session)?.username).toBe("alice2");
			expect(get(session)?.savedPlaces).toEqual([1]);
			const stored = JSON.parse(localStorage.getItem("btcmap_session") ?? "{}");
			expect(stored.username).toBe("alice2");
		});

		it("setNpub links and unlinks the Nostr identity and persists it", async () => {
			seedStorage({ username: "alice", token: "tok", savedPlaces: [] });
			const session = await createTestSession();
			session.init();

			session.setNpub(current, "npub1example");
			expect(get(session)?.npub).toBe("npub1example");
			expect(
				JSON.parse(localStorage.getItem("btcmap_session") ?? "{}").npub,
			).toBe("npub1example");

			session.setNpub(current, null);
			expect(get(session)?.npub).toBeNull();
		});

		// A response that lands after a logout, or after logging in to
		// another account, belongs to the account the request was made for
		it("both ignore a session for another account", async () => {
			seedStorage({ username: "bob", token: "other", savedPlaces: [] });
			const session = await createTestSession();
			session.init();

			session.setUsername(stale, "alice2");
			session.setNpub(stale, "npub1example");

			expect(get(session)?.username).toBe("bob");
			expect(get(session)?.npub).toBeNull();
		});

		it("both no-op without a session", async () => {
			const session = await createTestSession();

			session.setUsername(current, "alice");
			session.setNpub(current, "npub1example");

			expect(get(session)).toBeNull();
			expect(localStorage.getItem("btcmap_session")).toBeNull();
		});
	});

	describe("setSavedPlaces / setSavedAreas with null session", () => {
		it("setSavedPlaces warns and no-ops when session is null", async () => {
			const warnSpy = vi.spyOn(console, "warn").mockImplementation(() => {});
			const session = await createTestSession();

			session.setSavedPlaces([1, 2]);

			expect(get(session)).toBeNull();
			expect(warnSpy).toHaveBeenCalledWith(
				expect.stringContaining("setSavedPlaces"),
			);
		});

		it("setSavedAreas warns and no-ops when session is null", async () => {
			const warnSpy = vi.spyOn(console, "warn").mockImplementation(() => {});
			const session = await createTestSession();

			session.setSavedAreas([1, 2]);

			expect(get(session)).toBeNull();
			expect(warnSpy).toHaveBeenCalledWith(
				expect.stringContaining("setSavedAreas"),
			);
		});
	});
});

describe("isUsernameTaken", () => {
	const apiError = (status: number) =>
		new AxiosError("Request failed", "ERR_BAD_REQUEST", undefined, undefined, {
			status,
			statusText: "",
			data: { code: "conflict", message: "username already taken" },
			headers: {},
			config: { headers: new AxiosHeaders() },
		});

	// btcmap-api answers a taken name with 409 Conflict
	// (teambtcmap/btcmap-api#119)
	it("is true for a 409 from the API", async () => {
		const { isUsernameTaken } = await import("#lib/session.js");
		expect(isUsernameTaken(apiError(409))).toBe(true);
	});

	it("is false for any other failure", async () => {
		const { isUsernameTaken } = await import("#lib/session.js");
		expect(isUsernameTaken(apiError(500))).toBe(false);
		expect(isUsernameTaken(apiError(400))).toBe(false);
		expect(isUsernameTaken(new Error("offline"))).toBe(false);
	});
});
