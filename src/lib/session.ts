import { derived, get, writable } from "svelte/store";

import { API_BASE } from "#lib/api-base.js";
import { BadResponseError, errorStatus } from "#lib/apiError.js";
import type { AuthedClient } from "#lib/authedApi.js";
import api from "#lib/axios.js";

// Session is the BTC Map account behind saved places/areas. Accounts are
// created on /signup (or inline in the save prompt) with user-chosen
// credentials, or resumed via /login. The token is persisted in
// localStorage and used as a Bearer token on authenticated API calls.
//
// SECURITY — localStorage blast radius:
// The Bearer token is stored in localStorage, so an XSS could exfiltrate
// it. Never store a password next to it. DO NOT extend this pattern to
// accounts with durable data, payment info, or elevated roles. For
// those, migrate to httpOnly cookies or similar.
export type Session = {
	username: string;
	token: string;
	savedPlaces: number[];
	savedAreas: number[];
	// Bech32 npub of the linked Nostr identity, when the account was
	// authenticated via Nostr. null for password accounts.
	// Used to render the user's Nostr avatar/profile.
	npub: string | null;
};

// The client a request went out with: says whether its account is still
// the signed-in one
type SessionBound = Pick<AuthedClient, "stillCurrent">;

const STORAGE_KEY = "btcmap_session";

// Where other modules cache the signed-in account's data. Logout removes
// them with the session: they may be private (note text), and a page that
// never loads the owning module can't clear them itself.
export const ACCOUNT_CACHE_KEYS = { notes: "btcmap_my_notes" } as const;

function loadFromStorage(): Session | null {
	if (typeof window === "undefined") return null;
	try {
		const raw = localStorage.getItem(STORAGE_KEY);
		if (!raw) return null;
		const parsed = JSON.parse(raw);
		if (
			typeof parsed?.username !== "string" ||
			typeof parsed?.token !== "string" ||
			!Array.isArray(parsed?.savedPlaces)
		) {
			return null;
		}
		// Backfill savedAreas for sessions created before this field existed
		if (!Array.isArray(parsed.savedAreas)) {
			parsed.savedAreas = [];
		}
		// Backfill npub for sessions created before Nostr login existed.
		if (typeof parsed.npub !== "string") {
			parsed.npub = null;
		}
		// Legacy throwaway accounts (retired in #1325) stored a password
		// and an autoGenerated flag: drop both, from storage too, so the
		// password no longer sits in localStorage.
		if ("password" in parsed || "autoGenerated" in parsed) {
			delete parsed.password;
			delete parsed.autoGenerated;
			saveToStorage(parsed);
		}
		return parsed as Session;
	} catch {
		return null;
	}
}

function saveToStorage(session: Session | null) {
	if (typeof window === "undefined") return;
	try {
		if (session) {
			localStorage.setItem(STORAGE_KEY, JSON.stringify(session));
		} else {
			localStorage.removeItem(STORAGE_KEY);
			for (const key of Object.values(ACCOUNT_CACHE_KEYS)) {
				localStorage.removeItem(key);
			}
		}
	} catch (err) {
		console.warn("session: failed to persist to localStorage", err);
	}
}

// Credentials chosen on /signup or inline in the save prompt.
export type SignupCredentials = { username: string; password: string };

// Trims the username; a blank one is a caller bug.
function normalizeCredentials(
	credentials: SignupCredentials,
): SignupCredentials {
	const username = credentials.username.trim();
	if (!username || !credentials.password) {
		throw new Error("session.signUp: username and password must be non-empty");
	}
	return { username, password: credentials.password };
}

// The API refused the chosen username because another account has it:
// 409 Conflict (teambtcmap/btcmap-api#119)
export const isUsernameTaken = (error: unknown): boolean =>
	errorStatus(error) === 409;

// Mints a Bearer token for a user — the password authenticates the mint
// (sent as the Bearer on this one endpoint). Shared by login and signup.
export const mintToken = async (
	username: string,
	password: string,
): Promise<string> => {
	const res = await api.post(
		`${API_BASE}/v4/users/${encodeURIComponent(username)}/tokens`,
		{ label: "BTC Map Web" },
		{ headers: { Authorization: `Bearer ${password}` } },
	);
	const token = res.data?.token;
	if (typeof token !== "string" || !token) {
		throw new BadResponseError("token mint returned no token");
	}
	return token;
};

// The list with `id` added, or removed if it was already in it.
const toggled = (ids: number[], id: number): number[] =>
	ids.includes(id) ? ids.filter((x) => x !== id) : [...ids, id];

function createSessionStore() {
	const { subscribe, set, update } = writable<Session | null>(null);

	// Apply a change to the active session and persist it. A function change
	// is computed inside update(), against the session it replaces. Returns
	// whether a session was there to change.
	const patch = (
		change: Partial<Session> | ((current: Session) => Partial<Session>),
	): boolean => {
		let applied = false;
		update((current) => {
			if (!current) return current;
			applied = true;
			const next = {
				...current,
				...(typeof change === "function" ? change(current) : change),
			};
			saveToStorage(next);
			return next;
		});
		return applied;
	};

	const noSession = (method: string) =>
		console.warn(
			`session.${method} called with no active session — call signUp() first`,
		);

	const doSignUp = async (credentials: SignupCredentials): Promise<Session> => {
		// Straight against the API — it answers CORS preflights, so no
		// server proxy is involved and the flow works for any client, not
		// just the website (#1348). Two calls: create the account, then
		// mint a Bearer token (the password authenticates the mint).
		const userRes = await api.post(`${API_BASE}/v4/users`, {
			name: credentials.username,
			password: credentials.password,
		});
		const returnedUsername = userRes.data?.name;
		if (typeof returnedUsername !== "string" || !returnedUsername) {
			throw new BadResponseError("signup did not return a username");
		}

		const token = await mintToken(returnedUsername, credentials.password);

		const session: Session = {
			username: returnedUsername,
			token,
			savedPlaces: [],
			savedAreas: [],
			npub: null,
		};
		saveToStorage(session);
		set(session);
		return session;
	};

	return {
		subscribe,

		// The session, restored from localStorage the first time. The root
		// layout calls it on mount; a page that needs the session on its own
		// mount calls it too, because a child's onMount runs before the
		// layout's. Safe to call any number of times: a session already in
		// the store is kept, not re-read.
		init: (): Session | null => {
			const current = get({ subscribe });
			if (current) return current;
			const stored = loadFromStorage();
			if (stored) set(stored);
			return stored;
		},

		// Create an account with user-chosen credentials via the existing REST
		// endpoints. Rejects on a blank username. Double submits are the
		// form's job (its loading state disables the button).
		signUp: (credentials: SignupCredentials): Promise<Session> => {
			let normalized: SignupCredentials;
			try {
				normalized = normalizeCredentials(credentials);
			} catch (err) {
				return Promise.reject(err);
			}
			return doSignUp(normalized);
		},

		// Replace the savedPlaces array. Call after a successful PUT.
		setSavedPlaces: (ids: number[]) => {
			if (!patch({ savedPlaces: ids })) noSession("setSavedPlaces");
		},

		// Replace the savedAreas array. Call after a successful PUT.
		setSavedAreas: (ids: number[]) => {
			if (!patch({ savedAreas: ids })) noSession("setSavedAreas");
		},

		// Toggle a place in saved_places atomically. Computing the next list
		// inside the update() callback avoids a race when multiple buttons
		// read-modify-write concurrently (e.g. on a future "My Saved" list
		// view). Returns the resulting list so the caller can send it to the
		// server via PUT.
		toggleSavedPlace: (id: number): number[] | null => {
			let result: number[] | null = null;
			const applied = patch((current) => {
				result = toggled(current.savedPlaces, id);
				return { savedPlaces: result };
			});
			if (!applied) noSession("toggleSavedPlace");
			return result;
		},

		// Toggle an area in saved_areas atomically. Same pattern as toggleSavedPlace.
		toggleSavedArea: (id: number): number[] | null => {
			let result: number[] | null = null;
			const applied = patch((current) => {
				result = toggled(current.savedAreas, id);
				return { savedAreas: result };
			});
			if (!applied) noSession("toggleSavedArea");
			return result;
		},

		// The account was renamed on the API (account page). Like the other
		// account-page setters, it applies only while the session is still the
		// account the request was made for (`client`, authedApi.ts): a
		// response that lands after a logout or another login must not
		// rewrite that session.
		setUsername: (client: SessionBound, username: Session["username"]) => {
			if (client.stillCurrent()) patch({ username });
		},

		// A Nostr key was linked to (or unlinked from) the account on the API
		// (account page); drives the avatar like a Nostr login does.
		setNpub: (client: SessionBound, npub: Session["npub"]) => {
			if (client.stillCurrent()) patch({ npub });
		},

		// Replace the current session with a different account (login flow).
		// Saved items are populated separately after login. `npub` is set
		// for Nostr logins (drives the avatar), null for password logins.
		login: (username: string, token: string, npub: string | null = null) => {
			const session: Session = {
				username,
				token,
				savedPlaces: [],
				savedAreas: [],
				npub,
			};
			saveToStorage(session);
			set(session);
		},

		// Log out: clear the session first so logout never waits on the
		// network, then revoke the token on the API so a copy of it (see the
		// header comment) stops working. Best effort: offline or an
		// already-revoked token (401) leaves nothing to clean up.
		logout: async () => {
			const token = get({ subscribe })?.token;
			saveToStorage(null);
			set(null);
			if (!token) return;
			// The one user Bearer built outside authedApi.ts: the session is
			// already gone, and authedApi.ts reads its token from this store.
			try {
				await api.post(`${API_BASE}/v4/auth/signout`, null, {
					headers: { Authorization: `Bearer ${token}` },
				});
			} catch (err) {
				console.warn(
					"session: failed to revoke token on logout",
					errorStatus(err),
				);
			}
		},
	};
}

export const session = createSessionStore();

// Set of saved place IDs, kept in sync with the session store. Exposed as a
// Set so callers (e.g. the main map's marker factory) can O(1) lookup a
// place's saved state without scanning the savedPlaces array per marker.
export const savedPlaceIds = derived(
	session,
	($s) => new Set<number>($s?.savedPlaces ?? []),
);
